# Los gestores de geometría nos permiten establecer la posición relativa de los widgets 
# dentro de los marcos o la ventana principal. Existen tres tipos:
# El gestor pack() que se encarga de distribuir los widgets de un contenedor de forma
# automática según los parámetros de configuración. 
# El gestor grid() que se basa en el uso de una rejilla con filas y columnas para que
# el/la programador/a pueda decidir dónde posicionar los widgets. 
# El gestor place() que permite configurar las coordenadas (x, y) de cada widget para 
# establecer su posición dentro del contenedor.